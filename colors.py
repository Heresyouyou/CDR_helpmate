_GAMMA = (2.0, 4.0, 3.0)      # 绿权重最高，蓝次之，符合人眼


def hex_to_rgb(h):
    h = (h or "").strip().lstrip("#")
    if len(h) == 8:            # 有些接口给 AARRGGBB
        h = h[2:]
    if len(h) != 6:
        return None
    try:
        return (int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16))
    except Exception:
        return None


def rgb_to_hex(rgb):
    return "#%02X%02X%02X" % tuple(max(0, min(255, int(round(c)))) for c in rgb)


def _dist(a, b):
    return math.sqrt(sum(_GAMMA[i] * (a[i] - b[i]) ** 2 for i in range(3)))


_INDEX = [(name, hex_to_rgb(hx)) for name, hx in COLOR_TABLE]
_EXACT = {hx.upper(): name for name, hx in COLOR_TABLE}


def color_name(hex_value, fallback_prefix="色"):
    """返回 (色名, 是否精确命中)。"""
    hx = (hex_value or "").strip().upper()
    if hx and not hx.startswith("#"):
        hx = "#" + hx
    if hx in _EXACT:
        return _EXACT[hx], True
    rgb = hex_to_rgb(hx)
    if rgb is None:
        return "%s%s" % (fallback_prefix, (hex_value or "").strip("#")[:6]), False
    best = min(_INDEX, key=lambda item: _dist(rgb, item[1]))
    return best[0], False


def describe(hex_value):
    """给界面用：'鹅黄 #FFF176'"""
    name, _ = color_name(hex_value)
    return "%s %s" % (name, (hex_value or "").upper())
